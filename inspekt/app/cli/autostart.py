"""Autostart management for Inspekt (macOS LaunchAgent).

Provides commands to enable/disable automatic startup of the bridge
and API servers at login using a macOS LaunchAgent.
"""

import platform
import stat
import subprocess
import sys
from pathlib import Path

import click

from inspekt.app.cli.icons import get_indicator, get_status_icon
from inspekt.app.cli.table import Table, format_status_icon, print_hint

# Constants
LABEL = "com.inspekt.servers"
INSPEKT_DIR = Path.home() / ".inspekt"
LOGS_DIR = INSPEKT_DIR / "logs"
WRAPPER_PATH = INSPEKT_DIR / "autostart.sh"
PLIST_PATH = Path.home() / "Library" / "LaunchAgents" / f"{LABEL}.plist"


def _resolve_python() -> str:
    """Resolve the real Python executable path (not a pyenv shim).

    sys.executable already points to the real binary when running
    inside an activated environment, even through a pyenv shim.
    """
    return sys.executable


def _verify_python(python_path: str) -> bool:
    """Verify the resolved Python can import inspekt."""
    result = subprocess.run(
        [python_path, "-c", "import inspekt; print(inspekt.__version__)"],
        capture_output=True,
        text=True,
    )
    return result.returncode == 0


def _build_wrapper_script(python_path: str) -> str:
    """Generate the autostart wrapper shell script."""
    return f"""\
#!/bin/bash
# Inspekt autostart wrapper — generated by `inspekt autostart enable`
# Do not edit manually; re-run `inspekt autostart enable` to regenerate.

PYTHON="{python_path}"
PIDDIR="{INSPEKT_DIR}"

cleanup() {{
    kill "$BRIDGE_PID" "$API_PID" 2>/dev/null
    rm -f "$PIDDIR/bridge.pid" "$PIDDIR/api.pid"
    exit 0
}}
trap cleanup SIGTERM SIGINT

# --- Start bridge server ---
"$PYTHON" -m inspekt.bridge_ws &
BRIDGE_PID=$!
echo "$BRIDGE_PID" > "$PIDDIR/bridge.pid"

# Wait for bridge to become ready (max 10 seconds)
for i in $(seq 1 20); do
    if curl -s -o /dev/null http://127.0.0.1:8765/status 2>/dev/null; then
        break
    fi
    sleep 0.5
done

# --- Start API server ---
"$PYTHON" -m uvicorn inspekt.app.api.server:app --host 127.0.0.1 --port 8000 &
API_PID=$!
echo "$API_PID" > "$PIDDIR/api.pid"

# Keep wrapper alive while children run
wait
"""


def _build_plist(python_path: str) -> str:
    """Generate the LaunchAgent plist XML."""
    python_bin_dir = str(Path(python_path).parent)
    return f"""\
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN"
  "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
    <key>Label</key>
    <string>{LABEL}</string>

    <key>ProgramArguments</key>
    <array>
        <string>/bin/bash</string>
        <string>{WRAPPER_PATH}</string>
    </array>

    <key>RunAtLoad</key>
    <true/>

    <key>KeepAlive</key>
    <false/>

    <key>EnvironmentVariables</key>
    <dict>
        <key>PATH</key>
        <string>{python_bin_dir}:/usr/local/bin:/usr/bin:/bin</string>
        <key>HOME</key>
        <string>{Path.home()}</string>
        <key>INSPEKT_AUTOSTART</key>
        <string>1</string>
    </dict>

    <key>StandardOutPath</key>
    <string>{LOGS_DIR / "launchd.log"}</string>
    <key>StandardErrorPath</key>
    <string>{LOGS_DIR / "launchd.error.log"}</string>
</dict>
</plist>
"""


def _is_agent_loaded() -> bool:
    """Check whether the LaunchAgent is currently loaded."""
    result = subprocess.run(
        ["launchctl", "list", LABEL],
        capture_output=True,
    )
    return result.returncode == 0


def _read_embedded_python() -> str | None:
    """Read the Python path embedded in the existing wrapper script."""
    if not WRAPPER_PATH.exists():
        return None
    try:
        for line in WRAPPER_PATH.read_text().splitlines():
            if line.startswith('PYTHON="'):
                return line.split('"')[1]
    except OSError:
        pass
    return None


